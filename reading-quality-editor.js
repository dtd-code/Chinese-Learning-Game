window.polishReadingBank=function(data,raw,ctx){
 const sourceMap=new Map(raw.map(r=>[r[1],r]));
 const revised=data.map(l=>{
  const x=JSON.parse(JSON.stringify(l)),allowed=vocabularyFor(x,ctx),r=sourceMap.get(x.id);
  if(FIXES[x.id]){
   const patch=FIXES[x.id];
   if(patch.some(p=>!hasOnly(p,allowed)))throw Error("Editorial patch outside grade: "+x.id+" "+patch.map(p=>invalid(p,allowed)).join(""));
   x.story=patch.slice();
  }else{
   x.story=x.story.map(p=>normalize(p,allowed));
   const name=extractName(x.story);
   const moral=lessonMoral(r,x.story,allowed);
   x.story=endWithMoral(x.story,name,moral,allowed);
  }
  if(x.story.some(p=>!hasOnly(p,allowed)))throw Error("Story not verified: "+x.id);
  return x;
 });
 return revised;
};
