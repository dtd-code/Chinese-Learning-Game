function hasOnly(t,allowed){return [...String(t)].every(ch=>!HAN.test(ch)||allowed.has(ch))}
function invalid(t,allowed){return [...new Set([...String(t)].filter(ch=>HAN.test(ch)&&!allowed.has(ch)))].join("")}
function vocabularyFor(lesson,ctx){
 const seen=new Set(ctx.base3),course=lesson.unit.match(/^([456])[AB] 第(\d+)课/);
 const last=course?Number(course[2]):999;
 for(let g=4;g<=lesson.grade;g++){
  const total={4:16,5:15,6:10}[g];
  for(let n=1;n<=total;n++){
   if(g===lesson.grade&&n>last)break;
   const k=g+(n<=({4:9,5:8,6:6}[g])?"A":"B")+"-"+n;
   for(const ch of (ctx.read[k]||"")+(ctx.written[k]||""))seen.add(ch);
  }
 }
 return seen;
}
