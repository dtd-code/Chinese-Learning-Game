 let hit=-1;
 for(const marker of markers){const i=last.lastIndexOf(marker);if(i>hit)hit=i}
 // Keep the resolution; remove generic or irrelevant reflective conclusion.
 if(hit>=0){last=last.slice(0,hit+1)}
 else {
  const m=last.search(/(?:明白了|学会了|知道|我学到了|我学会了)[:：]/);
  if(m>=0){let p=last.lastIndexOf("。",m);if(p>=0)last=last.slice(0,p+1)}
 }
