 for(const [rx,opts] of MORAL_RULES)if(rx.test(key)){
  const v=opts.find(x=>hasOnly(x,allowed));
  if(v)return v;
 }
 return safeFirst(["有问题时要先想办法","朋友要互相帮助","要认真完成自己的事"],allowed,"要自己想办法");
